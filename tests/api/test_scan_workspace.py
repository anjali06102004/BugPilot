"""Phase 2 contracts: scan workspace data and single-finding exports.

The workspace shows the pages that were actually opened, the actions that were
performed (including blocked attempts), and the budgets the scan ran with.
"""

from __future__ import annotations

import asyncio
import uuid

import pytest
from app.main import app
from bugpilot_core.db import SessionLocal, init_db
from bugpilot_core.db.models import ActionRecord, Finding, PageRecord, Project, TestSession
from fastapi.testclient import TestClient

SEEDED: dict[str, str] = {}


async def seed_scan() -> tuple[str, str]:
    if SEEDED:
        return SEEDED["scan_id"], SEEDED["finding_id"]
    await init_db()
    async with SessionLocal() as db:
        project = Project(
            id=str(uuid.uuid4()),
            name="Workspace project",
            website_url="https://shop.example.com/",
            environment="staging",
        )
        session = TestSession(
            id=str(uuid.uuid4()),
            project_id=project.id,
            start_url="https://shop.example.com/cart",
            status="completed",
            scope_type="single_url",
            scope_json={"type": "single_url", "start_url": "https://shop.example.com/cart"},
            config_json={
                "max_pages": 1,
                "max_actions": 8,
                "max_duration_seconds": 60,
                "model_call_budget": 10,
            },
            pages_tested=1,
            actions_taken=2,
        )
        page = PageRecord(
            id=str(uuid.uuid4()),
            session_id=session.id,
            url="https://shop.example.com/cart",
            title="Cart",
            viewport_name="mobile-390",
            screenshot_path="data/evidence/session-page/shot.png",
        )
        performed = ActionRecord(
            id=str(uuid.uuid4()),
            session_id=session.id,
            type="click",
            description="click Buy now",
            selector="button.buy",
        )
        blocked = ActionRecord(
            id=str(uuid.uuid4()),
            session_id=session.id,
            type="navigate",
            description="navigate checkout",
            blocked=1,
            block_reason="Single URL scans do not follow links.",
        )
        finding = Finding(
            id=str(uuid.uuid4()),
            session_id=session.id,
            category="layout",
            title="Interactive elements overlap",
            description="Two controls overlap by 1160 square pixels.",
            severity="medium",
            priority="P2",
            confidence=0.91,
            confidence_label="confirmed",
            status="verified",
            source="layout_detector",
            url="https://shop.example.com/cart",
            route="/cart",
            expected="Controls remain independently clickable.",
            actual="Overlap area 1160 square pixels.",
            steps_json=["Open /cart at 390px", "Click the CTA"],
        )
        db.add_all([project, session, page, performed, blocked, finding])
        await db.commit()
        SEEDED["scan_id"] = session.id
        SEEDED["finding_id"] = finding.id
        return session.id, finding.id


@pytest.fixture(scope="module")
def client():
    with TestClient(app) as test_client:
        yield test_client


def test_scan_detail_includes_pages_actions_and_budgets(client):
    scan_id, _ = asyncio.run(seed_scan())
    payload = client.get(f"/api/v1/scans/{scan_id}").json()

    assert payload["pages"], "scan detail must include inspected pages"
    page = payload["pages"][0]
    assert page["url"] == "https://shop.example.com/cart"
    assert page["viewport_name"] == "mobile-390"
    assert page["screenshot"], "page screenshots should be signed evidence URLs"

    assert len(payload["actions"]) == 2
    blocked = [a for a in payload["actions"] if a["blocked"]]
    assert blocked and blocked[0]["block_reason"]

    assert payload["budgets"] == {
        "pages": 1,
        "actions": 8,
        "duration_seconds": 60,
        "model_calls": 10,
    }


def test_finding_markdown_export_contains_real_content(client):
    _, finding_id = asyncio.run(seed_scan())
    response = client.get(f"/api/v1/reports/finding/{finding_id}.md")
    assert response.status_code == 200
    assert response.headers["content-type"].startswith("text/markdown")
    assert "attachment" in response.headers["content-disposition"]
    body = response.text
    assert "Interactive elements overlap" in body
    assert "Two controls overlap" in body
    assert "Open /cart at 390px" in body
    assert "hypotheses unless marked confirmed" in body
    assert "Generated by BugPilot" in body


def test_finding_export_unknown_id_is_404(client):
    assert client.get("/api/v1/reports/finding/missing.md").status_code == 404
